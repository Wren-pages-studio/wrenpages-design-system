/**
 * Generates src/styles/tokens.css from src/tokens/*.ts.
 * Run with `npm run tokens` (also runs before dev/build). Never edit tokens.css by hand.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  palette,
  semanticColors,
  space,
  radius,
  borderWidth,
  size,
  zIndex,
  motion,
  shadow,
  iconStroke,
  fontFamily,
  fontWeight,
  lineHeight,
  textStyles,
  responsiveText,
  breakpoints,
  focusRing,
} from '../src/tokens/index';

const lines: string[] = [];
const section = (title: string) => lines.push('', `  /* ── ${title} ${'─'.repeat(Math.max(0, 44 - title.length))} */`);
const decl = (name: string, value: string | number) => lines.push(`  --${name}: ${value};`);

section('Primitives');
for (const [family, value] of Object.entries(palette)) {
  if (typeof value === 'string') decl(family, value);
  else for (const [step, hex] of Object.entries(value)) decl(`${family}-${step}`, hex);
}

section('Color · semantic (mode Light)');
for (const [group, tokens] of Object.entries(semanticColors)) {
  for (const [name, ref] of Object.entries(tokens)) {
    const [family, step] = (ref as string).split('.');
    decl(`color-${group}-${name}`, `var(--${family}-${step})`);
  }
}

section('Spacing (base 4)');
for (const [k, v] of Object.entries(space)) decl(`space-${k}`, v);

section('Radius & border');
for (const [k, v] of Object.entries(radius)) decl(`radius-${k}`, v);
for (const [k, v] of Object.entries(borderWidth)) decl(`border-width-${k}`, v);

section('Typography');
for (const [k, v] of Object.entries(fontFamily)) decl(`font-${k}`, v);
for (const [k, v] of Object.entries(fontWeight)) decl(`font-weight-${k}`, v);
for (const [k, v] of Object.entries(lineHeight)) decl(`line-height-${k}`, v);
for (const [name, s] of Object.entries(textStyles)) {
  decl(`text-${name}`, s.size);
  decl(`text-${name}-line-height`, s.lineHeight);
  decl(`text-${name}-tracking`, s.tracking);
  decl(`text-${name}-weight`, `var(--font-weight-${s.weight})`);
  decl(`text-${name}-family`, `var(--font-${s.family})`);
}

section('Sizes');
for (const [k, v] of Object.entries(size)) decl(`size-${k}`, v);
decl('container', 'var(--size-container)');

section('Effects');
for (const [k, v] of Object.entries(shadow)) decl(`shadow-${k}`, v);
decl('focus-ring', focusRing);
for (const [k, v] of Object.entries(iconStroke)) decl(`icon-stroke-${k}`, v);

section('Motion');
for (const [k, v] of Object.entries(motion)) decl(k, v);

section('Layers');
for (const [k, v] of Object.entries(zIndex)) decl(`z-${k}`, v);

const css = `/* Wren Pages — design tokens.
   AUTO-GENERATED by scripts/generate-tokens.ts from src/tokens/*.ts — do not edit by hand. */

:root {${lines.join('\n')}
}
`;

const out = fileURLToPath(new URL('../src/styles/tokens.css', import.meta.url));
writeFileSync(out, css);
console.log(`tokens.css written (${lines.filter((l) => l.includes('--')).length} custom properties)`);

/* ── Typography classes (.wp-text--<style> and responsive roles) ───────── */
const textRule = (selector: string, style: string, indent = '') =>
  [
    `${indent}${selector} {`,
    `${indent}  font-family: var(--text-${style}-family);`,
    `${indent}  font-size: var(--text-${style});`,
    `${indent}  font-weight: var(--text-${style}-weight);`,
    `${indent}  line-height: var(--text-${style}-line-height);`,
    `${indent}  letter-spacing: var(--text-${style}-tracking);`,
    ...((textStyles[style as keyof typeof textStyles] as { uppercase?: boolean }).uppercase
      ? [`${indent}  text-transform: uppercase;`]
      : []),
    `${indent}}`,
  ].join('\n');

const typo: string[] = [];
for (const name of Object.keys(textStyles)) typo.push(textRule(`.wp-text--${name}`, name));
for (const [role, [m]] of Object.entries(responsiveText)) typo.push(textRule(`.wp-text--${role}`, m));
for (const [bp, idx] of [
  [breakpoints.tablet, 1],
  [breakpoints.desktop, 2],
] as const) {
  const rules = Object.entries(responsiveText)
    .filter(([, styles]) => styles[idx] !== styles[idx - 1])
    .map(([role, styles]) => textRule(`.wp-text--${role}`, styles[idx], '  '));
  typo.push(`@container page (min-width: ${bp}px) {\n${rules.join('\n\n')}\n}`);
}

writeFileSync(
  fileURLToPath(new URL('../src/styles/typography.css', import.meta.url)),
  `/* Wren Pages — text styles (Figma text styles → classes).
   AUTO-GENERATED by scripts/generate-tokens.ts — do not edit by hand. */

${typo.join('\n\n')}
`,
);
console.log('typography.css written');
